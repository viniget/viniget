package desktop

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/viniget/viniget/internal/wine"
)

// A generated launcher script sits between the .desktop entry and wine.
//
// It exists for four reasons, none of which a bare `Exec=env WINEPREFIX=...
// wine app.exe %f` line can cover. A Windows application handed
// /home/you/report.pdf cannot open it -- the argument has to be converted to
// the prefix's own drive letters first. Several applications only work when
// launched from their install directory. A few will not start at all without
// a WINEDLLOVERRIDES, which then has to be present on every launch rather
// than remembered by whoever first reported the bug. And the whole command is
// then one argument in the Exec line rather than eight, which keeps the two
// layers of quoting the Exec key requires down to something a person can
// read.
//
// The script is derived state: it is regenerated from the prefix whenever it
// is missing, and editing it by hand is pointless.

// Launcher starts one installed application.
type Launcher struct {
	// ID is the winget package identifier, for the comment header.
	ID string
	// Prefix is the WINEPREFIX the application lives in.
	Prefix string
	// Target is the host path of the executable.
	Target string
	// Args are the fixed arguments the shortcut carried, ahead of any files
	// the desktop passes in.
	Args []string
	// WorkingDir is the host directory to launch from. Empty means the
	// executable's own directory.
	WorkingDir string
	// DLLOverrides is a WINEDLLOVERRIDES string for an application that needs
	// one to start. Empty -- which is nearly always -- means wine's defaults.
	DLLOverrides string
}

// dosTarget renders the executable as the prefix sees it.
//
// Addressing the executable as C:\... rather than by host path matters:
// launched through Z:, an application sees itself installed on a network
// drive, and the ones that resolve their own resources or registry keys
// relative to their module path get it wrong.
func (l *Launcher) dosTarget() string {
	if dos, err := wine.DOSPath(l.Prefix, l.Target); err == nil {
		return dos
	}
	return l.Target
}

func (l *Launcher) workingDir() string {
	if l.WorkingDir != "" {
		return l.WorkingDir
	}
	return filepath.Dir(l.Target)
}

// Script renders the launcher as a POSIX shell script.
func (l *Launcher) Script() []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "#!/bin/sh\n")
	fmt.Fprintf(&b, "# Generated by viniget for %s -- rewritten by: viniget desktop %s\n", l.ID, l.ID)
	fmt.Fprintf(&b, "#\n")
	fmt.Fprintf(&b, "# Any host path passed in is converted to the prefix's drive letters first:\n")
	fmt.Fprintf(&b, "# a Windows application handed /home/you/report.pdf cannot open it.\n\n")

	fmt.Fprintf(&b, "WINEPREFIX=%s\n", shellQuote(l.Prefix))
	fmt.Fprintf(&b, "export WINEPREFIX\n")
	// Left overridable rather than forced: wine's fixme chatter goes to the
	// session journal where nobody reads it, but somebody debugging a launch
	// needs it back without editing the file.
	fmt.Fprintf(&b, "WINEDEBUG=${WINEDEBUG--all}\n")
	fmt.Fprintf(&b, "export WINEDEBUG\n")
	if l.DLLOverrides != "" {
		// Overridable for the same reason, and more so: this one is viniget's
		// opinion about a wine bug rather than a fact about the application,
		// and whoever checks whether the bug is still there needs to drop it
		// for one run without editing a generated file.
		fmt.Fprintf(&b, "WINEDLLOVERRIDES=${WINEDLLOVERRIDES-%s}\n", shellQuote(l.DLLOverrides))
		fmt.Fprintf(&b, "export WINEDLLOVERRIDES\n")
	}
	fmt.Fprintf(&b, "\n")
	fmt.Fprintf(&b, "cd %s 2>/dev/null || :\n\n", shellQuote(l.workingDir()))

	fmt.Fprintf(&b, "# Rotate the argument list, converting the host paths in it as they go by.\n")
	fmt.Fprintf(&b, "n=$#\n")
	fmt.Fprintf(&b, "while [ \"$n\" -gt 0 ]; do\n")
	fmt.Fprintf(&b, "\targ=$1\n\tshift\n")
	fmt.Fprintf(&b, "\tif [ -e \"$arg\" ]; then\n")
	fmt.Fprintf(&b, "\t\twin=$(winepath -w \"$arg\" 2>/dev/null) && arg=$win\n")
	fmt.Fprintf(&b, "\tfi\n")
	fmt.Fprintf(&b, "\tset -- \"$@\" \"$arg\"\n")
	fmt.Fprintf(&b, "\tn=$((n - 1))\n")
	fmt.Fprintf(&b, "done\n\n")

	fmt.Fprintf(&b, "exec wine %s", shellQuote(l.dosTarget()))
	for _, a := range l.Args {
		fmt.Fprintf(&b, " %s", shellQuote(a))
	}
	fmt.Fprintf(&b, " \"$@\"\n")
	return []byte(b.String())
}

// Write installs the launcher script and returns its path.
func (l *Launcher) Write(dir, name string) (string, error) {
	path := filepath.Join(dir, name)
	return path, writeFile(path, l.Script(), 0o755)
}

// ExecLine renders the Exec value for a .desktop entry pointing at script.
//
// %F rather than %f: every application viniget generates an entry for is a
// real Windows program with a command line, so one that can be handed several
// files at once should be. The field code is present even on an entry that
// advertises no file types, because a file dragged onto a launcher arrives the
// same way an association does.
func ExecLine(script string) string {
	return execArg(script) + " %F"
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// SplitWindowsArgs splits a shortcut's argument string into argv.
//
// This is the lenient reading of Windows command-line parsing: quotes group,
// whitespace separates, and backslash is a path separator rather than an
// escape. The strict rules only differ for backslash runs before a quote,
// which shortcut arguments do not contain -- and reading a path's backslashes
// as escapes would be far worse than the case it fixes.
func SplitWindowsArgs(s string) []string {
	var (
		out    []string
		cur    strings.Builder
		quoted bool
		filled bool
	)
	flush := func() {
		if filled || cur.Len() > 0 {
			out = append(out, cur.String())
			cur.Reset()
			filled = false
		}
	}
	for _, r := range s {
		switch {
		case r == '"':
			quoted = !quoted
			filled = true
		case (r == ' ' || r == '\t') && !quoted:
			flush()
		default:
			cur.WriteRune(r)
		}
	}
	flush()
	return out
}

// LauncherName is the filename a package's launcher script is written under.
func LauncherName(id, suffix string) string {
	if suffix == "" {
		return id
	}
	return id + "-" + suffix
}

// removeIfPresent deletes a path, ignoring the "it was already gone" case.
func removeIfPresent(path string) error {
	err := os.Remove(path)
	if os.IsNotExist(err) {
		return nil
	}
	return err
}
